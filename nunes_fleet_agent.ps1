function Get-SystemTelemetry {















    $comp = $env:COMPUTERNAME















    $user = $env:USERNAME















    















    # OS info (CIM with WMI fallback for Windows 7)















    $osName = "Windows"















    try {















        if (Get-Command Get-CimInstance -ErrorAction SilentlyContinue) {















            $osInfo = Get-CimInstance Win32_OperatingSystem -ErrorAction SilentlyContinue















            if ($osInfo) { $osName = $osInfo.Caption }















        } else {















            $osInfo = Get-WmiObject Win32_OperatingSystem -ErrorAction SilentlyContinue















            if ($osInfo) { $osName = $osInfo.Caption }















        }















    } catch {}















    if (-not $osName -or $osName -eq "Windows") {















        $osName = [System.Environment]::OSVersion.VersionString















    }































    # Disk info (CIM with WMI fallback for Windows 7)















    $diskFreeGb = 10.0















    $diskTotalGb = 120.0















    $diskUsedPct = 50.0















    try {















        $disk = $null















        if (Get-Command Get-CimInstance -ErrorAction SilentlyContinue) {















            $disk = Get-CimInstance Win32_LogicalDisk -Filter "DeviceID='C:'" -ErrorAction SilentlyContinue















        } else {















            $disk = Get-WmiObject Win32_LogicalDisk -Filter "DeviceID='C:'" -ErrorAction SilentlyContinue















        }















        if ($disk -and $disk.Size -gt 0) {















            $diskFreeGb = [math]::Round($disk.FreeSpace / 1GB, 2)















            $diskTotalGb = [math]::Round($disk.Size / 1GB, 2)















            $diskUsedGb = $diskTotalGb - $diskFreeGb















            $diskUsedPct = [math]::Round(($diskUsedGb / $diskTotalGb) * 100, 1)















        }















    } catch {}































    # Network IP discovery















    $ipAddresses = @()















    try {















        $dnsHost = [System.Net.Dns]::GetHostEntry([System.Net.Dns]::GetHostName())















        $ipAddresses = $dnsHost.AddressList | 















            Where-Object { $_.AddressFamily -eq 'InterNetwork' -and $_.IPAddressToString -ne '127.0.0.1' } |















            ForEach-Object { $_.IPAddressToString }















    } catch {}































    $lanIp = if ($ipAddresses) { ($ipAddresses | Select-Object -First 1) } else { "127.0.0.1" }















    $tsIp = ($ipAddresses | Where-Object { $_ -match "^100\." } | Select-Object -First 1)















    if (-not $tsIp) { $tsIp = "-" }































    $nowIso = (Get-Date).ToUniversalTime().ToString("o")















    return @{















        Computer = $comp















        User = $user















        OS = $osName















        DiskFreeGB = $diskFreeGb















        DiskTotalGB = $diskTotalGb















        DiskPercentUsed = $diskUsedPct















        LocalIPv4 = $lanIp















        TailscaleIP = $tsIp















        TailscaleUp = ($tsIp -ne "-")















        LastSeenUtc = $nowIso















    }















}































function Invoke-SafeCleanmgr {















    param([int]$TimeoutSec = 15)































    # Configure VolumeCaches StateFlags for Safe Group 65535















    $regBase = "HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Explorer\VolumeCaches"















    $safeHandlers = @(















        "Active Setup Temp Folders", "BranchCache", "Delivery Optimization Files",















        "Device Driver Packages", "Diagnostic Data Viewer database files",















        "Downloaded Program Files", "Internet Cache Files", "Old ChkDsk Files",















        "RetailDemo Offline Content", "Setup Log Files", "System error memory dump files",















        "System error minidump files", "Temporary Files", "Temporary Setup Files",















        "Thumbnail Cache", "Windows Error Reporting Archive Files",















        "Windows Error Reporting Queue Files", "Windows Error Reporting System Archive Files",















        "Windows Error Reporting System Queue Files", "Windows Upgrade Log Files"















    )































    try {















        foreach ($handler in $safeHandlers) {















            $hPath = "$regBase\$handler"















            if (Test-Path $hPath) {















                Set-ItemProperty -Path $hPath -Name "StateFlags65535" -Value 2 -Type DWord -Force -ErrorAction SilentlyContinue















            }















        }















        # EXPLICIT SAFETY SAFEGUARD: NEVER delete Downloads or Recycle Bin















        foreach ($excluded in @("DownloadsFolder", "Update Cleanup", "Recycle Bin")) {















            $ePath = "$regBase\$excluded"















            if (Test-Path $ePath) {















                Set-ItemProperty -Path $ePath -Name "StateFlags65535" -Value 0 -Type DWord -Force -ErrorAction SilentlyContinue















            }















        }















    } catch {}































    # Run cleanmgr silently in background















    $cleanmgrPath = "$env:SystemRoot\System32\cleanmgr.exe"















    if (Test-Path $cleanmgrPath) {















        try {















            $proc = Start-Process -FilePath $cleanmgrPath -ArgumentList "/sagerun:65535" -NoNewWindow -PassThru -ErrorAction Stop















            $proc | Wait-Process -Timeout $TimeoutSec -ErrorAction SilentlyContinue















            if (-not $proc.HasExited) {















                $proc | Stop-Process -Force -ErrorAction SilentlyContinue















            }















        } catch {















            try {















                $proc = Start-Process -FilePath $cleanmgrPath -ArgumentList "/autoclean" -NoNewWindow -PassThru -ErrorAction SilentlyContinue















                $proc | Wait-Process -Timeout 30 -ErrorAction SilentlyContinue















                if (-not $proc.HasExited) {















                    $proc | Stop-Process -Force -ErrorAction SilentlyContinue















                }















            } catch {}















        }















    }















}































function Invoke-SystemClean {















    param([switch]$RunCleanmgr = $true)































    $deletedFiles = 0















    $reclaimedBytes = 0































    # 1. Clean User TEMP (%TEMP%)















    Write-Host "   [1/3] Purging User TEMP (%TEMP%)..." -ForegroundColor Cyan















    if (Test-Path $env:TEMP) {















        try {















            $items = Get-ChildItem -Path $env:TEMP -Recurse -File -Force -ErrorAction SilentlyContinue















            foreach ($item in $items) {















                try {















                    $len = $item.Length















                    Remove-Item -Path $item.FullName -Force -ErrorAction Stop















                    $deletedFiles++















                    $reclaimedBytes += $len















                } catch {}















            }















            Get-ChildItem -Path $env:TEMP -Recurse -Directory -Force -ErrorAction SilentlyContinue |















                Sort-Object -Property FullName -Descending |















                ForEach-Object { Remove-Item -Path $_.FullName -Force -Recurse -ErrorAction SilentlyContinue }















        } catch {}















    }































    # 2. Clean Windows TEMP (C:\Windows\Temp)















    Write-Host "   [2/3] Purging Windows TEMP (C:\Windows\Temp)..." -ForegroundColor Cyan















    $winTemp = "$env:SystemRoot\Temp"















    if (Test-Path $winTemp) {















        try {















            $items = Get-ChildItem -Path $winTemp -Recurse -File -Force -ErrorAction SilentlyContinue















            foreach ($item in $items) {















                try {















                    $len = $item.Length















                    Remove-Item -Path $item.FullName -Force -ErrorAction Stop















                    $deletedFiles++















                    $reclaimedBytes += $len















                } catch {}















            }















            Get-ChildItem -Path $winTemp -Recurse -Directory -Force -ErrorAction SilentlyContinue |















                Sort-Object -Property FullName -Descending |















                ForEach-Object { Remove-Item -Path $_.FullName -Force -Recurse -ErrorAction SilentlyContinue }















        } catch {}















    }































    # Fast Python Multi-Profile Cleaner invocation (if available)















    $cleanerPy = Join-Path $PSScriptRoot "cleaner.py"















    if ((Test-Path $cleanerPy) -and (Get-Command python -ErrorAction SilentlyContinue)) {















        try {















            Write-Host "   [*] Invoking Fast Python Engine for multi-profile caches..." -ForegroundColor Cyan















            $jsonOut = & python -u $cleanerPy --no-cleanmgr --json 2>$null















            if ($jsonOut) {















                $pyRes = $jsonOut | ConvertFrom-Json















                $deletedFiles += $pyRes.deleted















                $reclaimedBytes += ($pyRes.recovered_mb * 1MB)















            }















        } catch {}















    }































    # Extra Safe Caches: Browsers, Shaders, CrashDumps















    $extraCaches = @(















        "$env:LOCALAPPDATA\CrashDumps",















        "$env:ProgramData\Microsoft\Windows\WER\ReportQueue",















        "$env:ProgramData\Microsoft\Windows\WER\ReportArchive",















        "$env:LOCALAPPDATA\Google\Chrome\User Data\Default\Cache",















        "$env:LOCALAPPDATA\Google\Chrome\User Data\Default\Code Cache",















        "$env:LOCALAPPDATA\Microsoft\Edge\User Data\Default\Cache",















        "$env:LOCALAPPDATA\Microsoft\Edge\User Data\Default\Code Cache",















        "$env:LOCALAPPDATA\D3DSCache",















        "$env:LOCALAPPDATA\NVIDIA\DXCache",















        "$env:LOCALAPPDATA\pip\cache"















    )















    foreach ($dir in $extraCaches) {















        if (Test-Path $dir) {















            try {















                $items = Get-ChildItem -Path $dir -Recurse -File -Force -ErrorAction SilentlyContinue















                foreach ($item in $items) {















                    try {















                        $len = $item.Length















                        Remove-Item -Path $item.FullName -Force -ErrorAction Stop















                        $deletedFiles++















                        $reclaimedBytes += $len















                    } catch {}















                }















            } catch {}















        }















    }































    # 3. Windows Deep Disk Cleanup (cleanmgr.exe)















    if ($RunCleanmgr) {















        Write-Host "   [3/4] Running Windows Disk Cleanup (cleanmgr.exe safe mode)..." -ForegroundColor Cyan















        Invoke-SafeCleanmgr -TimeoutSec 60







    }















    # 4. 30-Day Retention Sweep: Automatically purge prompt/log backups older than 30 days







    Write-Host "   [4/4] Enforcing 30-Day Retention Lifecycle (purging items older than 30 days)..." -ForegroundColor Cyan







    $retentionLimit = (Get-Date).AddDays(-30)







    $backupDirs = @(







        "$env:ProgramData\NunesCleanerV7\Backups",







        "$env:ProgramData\NunesCleanerV7\PromptBackups",







        (Join-Path $PSScriptRoot "dashboard\data\prompt_backups")







    )







    foreach ($bDir in $backupDirs) {







        if (Test-Path $bDir) {







            try {







                Get-ChildItem -Path $bDir -File -Force -ErrorAction SilentlyContinue |







                    Where-Object { $_.LastWriteTime -lt $retentionLimit } |







                    ForEach-Object {







                        Remove-Item -Path $_.FullName -Force -ErrorAction SilentlyContinue







                        $deletedFiles++







                    }







            } catch {}







        }















    }































    $reclaimedMb = [math]::Round($reclaimedBytes / 1MB, 2)















    return @{















        DeletedFiles = $deletedFiles















        ReclaimedMB = $reclaimedMb















    }















}































function Send-UniversalJsonGet {
    param(
        [Parameter(Mandatory=$true)][string]$Url,
        [int]$TimeoutSeconds = 3
    )
    if (Get-Command Invoke-RestMethod -ErrorAction SilentlyContinue) {
        try {
            return (Invoke-RestMethod -Uri $Url -Method Get -TimeoutSec $TimeoutSeconds -ErrorAction Stop)
        } catch {}
    }
    try {
        $wc = New-Object System.Net.WebClient
        $wc.Headers.Add("User-Agent", "NunesFleetAgent/10.1 (Windows; Universal)")
        $raw = $wc.DownloadString($Url)
        if ($raw -and (Get-Command ConvertFrom-Json -ErrorAction SilentlyContinue)) {
            return ($raw | ConvertFrom-Json)
        }
    } catch {}
    return $null
}

function Send-UniversalJsonPost {















    param(















        [string]$Url,















        [string]$JsonPayload,















        [int]$TimeoutSeconds = 4















    )































    # Attempt 1: Invoke-RestMethod (PowerShell 3.0+)















    if (Get-Command Invoke-RestMethod -ErrorAction SilentlyContinue) {















        try {















            return (Invoke-RestMethod -Uri $Url -Method Post -Body $JsonPayload -ContentType "application/json; charset=utf-8" -TimeoutSec $TimeoutSeconds -ErrorAction Stop)















        } catch {}















    }































    # Attempt 2: System.Net.WebClient (Universal .NET 2.0+ / Windows 7/8/10/11)















    try {















        $wc = New-Object System.Net.WebClient















        $wc.Headers.Add("Content-Type", "application/json; charset=utf-8")















        $wc.Headers.Add("User-Agent", "NunesFleetAgent/7.4.0")















        $wc.Encoding = [System.Text.Encoding]::UTF8















        $responseStr = $wc.UploadString($Url, $JsonPayload)















        $wc.Dispose()















        if ($responseStr) {















            if (Get-Command ConvertFrom-Json -ErrorAction SilentlyContinue) {















                return ($responseStr | ConvertFrom-Json)















            } else {















                return @{ success = ($responseStr -match '"success"\s*:\s*true') }















            }















        }















    } catch {}































    # Attempt 3: Built-in curl.exe (Windows 10 1803+)















    $curlPath = "$env:SystemRoot\System32\curl.exe"















    if (Test-Path $curlPath) {















        try {















            $tmpFile = [System.IO.Path]::GetTempFileName()















            [System.IO.File]::WriteAllText($tmpFile, $JsonPayload, [System.Text.Encoding]::UTF8)















            $respText = & $curlPath -s -m $TimeoutSeconds -X POST $Url -H "Content-Type: application/json" -d "@$tmpFile"















            Remove-Item $tmpFile -Force -ErrorAction SilentlyContinue















            if ($respText -and (Get-Command ConvertFrom-Json -ErrorAction SilentlyContinue)) {















                return ($respText | ConvertFrom-Json)















            }















        } catch {}















    }































    return $null















}
































